package io.github.litheidea.tomcat;

import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.BasicFileAttributes;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Locale;

/**
 * The private CATALINA_BASE one Web module runs in, under the workspace
 * state directory Lithe gives the build system:
 * {@code <state>/bases/<hash of instance root and module path>}.
 *
 * <p>Each preparation rewrites {@code conf/}: {@code server.xml} with one
 * HTTP connector on the loopback address and no shutdown port, a copy of
 * a console-only {@code logging.properties}, a copy of the other top-level
 * files of the installation's {@code conf/}, and one context file that
 * points at the module. {@code work/} (compiled JSPs) is
 * kept between runs; {@code webapps/} is emptied, so a rebuilt WAR is
 * expanded again. The installation itself is only read, and nothing goes
 * into the workspace, the plugin package or the installation.
 */
final class CatalinaBase {
    /**
     * Tomcat's logging for a Lithe run: the console only, which Lithe shows in
     * the Run window, at Tomcat's usual INFO level. The installation's file
     * handlers would write dated log files into the workspace state, which is
     * not a log directory, so they are left out.
     */
    static final String LOGGING = "# Generated by the Lithe Tomcat plugin; rewritten on every start.\n"
            + "handlers = java.util.logging.ConsoleHandler\n"
            + ".handlers = java.util.logging.ConsoleHandler\n"
            + ".level = INFO\n"
            + "java.util.logging.ConsoleHandler.level = FINE\n"
            + "java.util.logging.ConsoleHandler.formatter = org.apache.juli.OneLineFormatter\n"
            + "java.util.logging.ConsoleHandler.encoding = UTF-8\n";

    final Path directory;

    private CatalinaBase(Path directory) {
        this.directory = directory;
    }

    static CatalinaBase write(Path state, Path home, String key, int httpPort, String contextPath,
            Path docBase, Path classes) throws IOException {
        Path base = state.resolve("bases").resolve(hash(key));
        Path conf = base.resolve("conf");
        Files.createDirectories(conf);
        for (String folder : new String[] {"temp", "work", "webapps"}) {
            Files.createDirectories(base.resolve(folder));
        }
        clear(base.resolve("webapps"));
        clear(base.resolve("temp"));
        clear(conf);
        try (DirectoryStream<Path> files = Files.newDirectoryStream(home.resolve("conf"))) {
            for (Path file : files) {
                String name = file.getFileName().toString();
                if (Files.isRegularFile(file) && !name.equals("server.xml") && !name.equals("logging.properties")) {
                    Files.copy(file, conf.resolve(name), StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
        writeText(conf.resolve("server.xml"), serverXml(httpPort));
        writeText(conf.resolve("logging.properties"), LOGGING);
        Path contexts = conf.resolve("Catalina").resolve("localhost");
        Files.createDirectories(contexts);
        writeText(contexts.resolve(contextFileName(contextPath) + ".xml"), contextXml(docBase, classes));
        return new CatalinaBase(base);
    }

    static String serverXml(int httpPort) {
        return "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                + "<!-- Generated by the Lithe Tomcat plugin for one run; rewritten on every start. -->\n"
                + "<Server port=\"-1\" shutdown=\"SHUTDOWN\">\n"
                + "  <Listener className=\"org.apache.catalina.startup.VersionLoggerListener\" />\n"
                + "  <Listener className=\"org.apache.catalina.core.JreMemoryLeakPreventionListener\" />\n"
                + "  <Listener className=\"org.apache.catalina.core.ThreadLocalLeakPreventionListener\" />\n"
                + "  <Service name=\"Catalina\">\n"
                + "    <Connector port=\"" + httpPort + "\" address=\"127.0.0.1\" protocol=\"HTTP/1.1\"\n"
                + "               connectionTimeout=\"20000\" />\n"
                + "    <Engine name=\"Catalina\" defaultHost=\"localhost\">\n"
                + "      <Host name=\"localhost\" appBase=\"webapps\" unpackWARs=\"true\" autoDeploy=\"false\" />\n"
                + "    </Engine>\n"
                + "  </Service>\n"
                + "</Server>\n";
    }

    /**
     * The context of the module: {@code docBase} is the exploded application
     * or the WAR, and compiled classes outside it are mounted at
     * {@code /WEB-INF/classes} ahead of the application's own, with class
     * reloading on, as Eclipse WTP serves a Dynamic Web Project.
     */
    static String contextXml(Path docBase, Path classes) {
        StringBuilder xml = new StringBuilder();
        xml.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        xml.append("<Context docBase=\"").append(attribute(docBase.toString())).append('"');
        if (classes == null) {
            xml.append(" />\n");
            return xml.toString();
        }
        xml.append(" reloadable=\"true\">\n");
        xml.append("  <Resources>\n");
        xml.append("    <PreResources className=\"org.apache.catalina.webresources.DirResourceSet\"\n");
        xml.append("                  base=\"").append(attribute(classes.toString())).append("\"\n");
        xml.append("                  webAppMount=\"/WEB-INF/classes\" />\n");
        xml.append("  </Resources>\n");
        xml.append("</Context>\n");
        return xml.toString();
    }

    /** {@code ROOT} for the root context, otherwise the path with {@code #} for {@code /}. */
    static String contextFileName(String contextPath) {
        String path = contextPath.startsWith("/") ? contextPath.substring(1) : contextPath;
        return path.isEmpty() ? "ROOT" : path.replace('/', '#');
    }

    static String attribute(String value) {
        return value.replace("&", "&amp;").replace("\"", "&quot;").replace("<", "&lt;").replace(">", "&gt;");
    }

    private static void writeText(Path file, String text) throws IOException {
        Path partial = Files.createTempFile(file.getParent(), file.getFileName().toString(), ".tmp");
        try (Writer writer = Files.newBufferedWriter(partial, StandardCharsets.UTF_8)) {
            writer.write(text);
        }
        Files.move(partial, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
    }

    /** Deletes what {@code directory} holds; links are removed, never followed. */
    static void clear(Path directory) throws IOException {
        try (DirectoryStream<Path> entries = Files.newDirectoryStream(directory)) {
            for (Path entry : entries) {
                if (Files.isDirectory(entry) && !Files.isSymbolicLink(entry)) {
                    Files.walkFileTree(entry, new SimpleFileVisitor<Path>() {
                        @Override
                        public FileVisitResult visitFile(Path file, BasicFileAttributes attributes) throws IOException {
                            Files.delete(file);
                            return FileVisitResult.CONTINUE;
                        }

                        @Override
                        public FileVisitResult postVisitDirectory(Path visited, IOException failure) throws IOException {
                            if (failure != null) {
                                throw failure;
                            }
                            Files.delete(visited);
                            return FileVisitResult.CONTINUE;
                        }
                    });
                } else {
                    Files.delete(entry);
                }
            }
        }
    }

    static String hash(String text) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8));
            StringBuilder hex = new StringBuilder();
            for (int index = 0; index < 8; index++) {
                hex.append(String.format(Locale.ROOT, "%02x", digest[index]));
            }
            return hex.toString();
        } catch (NoSuchAlgorithmException impossible) {
            throw new IllegalStateException(impossible);
        }
    }
}
